"""
Исключения модуля парсинга учебных планов.

Предоставляет чистую иерархию исключений для синтаксического анализа,
валидации безопасности и валидации структуры учебных планов.
"""


class CurriculumParsingError(Exception):
    """Базовое исключение при ошибках синтаксического анализа и валидации учебных планов."""
    pass


class PLXParsingError(CurriculumParsingError):
    """
    Исключение при ошибках чтения или парсинга формата PLX / XML.
    Сохранено для 100% обратной совместимости с существующим кодом.
    """
    pass


class SecurityValidationError(PLXParsingError):
    """Исключение при обнаружении уязвимостей безопасности (XXE, DTD инъекции и т.д.)."""
    pass


class EmptyPlanError(PLXParsingError):
    """Исключение при передаче пустого файла или файла без содержимого."""
    pass
